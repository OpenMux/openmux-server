"""Shared identity resolver tests (ticket #74).

``server.id`` is the sole identity key. The resolver ignores the removed
``name`` / ``server_id`` keys (callers fall back to the hostname, which the
callers supply), and the ConfigManager deprecation shim detects and strips
those keys from a loaded config (shim tests live in tests/test_locations.py).
"""

import hashlib
import logging
import socket

from openmux.common.identity import (
    CERT_CN_DIGEST_LEN,
    CERT_CN_MAX_LEN,
    CERT_CN_TRUNCATION_MARK,
    certificate_cn,
    get_server_id,
    get_server_label,
    warn_long_server_id,
)

FAKE_HOST = "fake-host-74"
FAKE_HOSTNAME = "fallback-host-74"


def test_get_server_id_uses_id():
    assert get_server_id({"id": "node-1"}) == "node-1"
    # Whitespace is stripped; blank values are treated as unset.
    assert get_server_id({"id": "  node-1  "}) == "node-1"
    assert get_server_id({"id": "   "}) is None
    assert get_server_id({"id": ""}) is None
    # Non-string values are coerced to str (a YAML int id still works).
    assert get_server_id({"id": 7}) == "7"


def test_get_server_id_ignores_removed_keys():
    # The removed fallback keys are not identity (ticket #74); None means the
    # caller falls back to the system hostname.
    assert get_server_id({"name": "leaf-1"}) is None
    assert get_server_id({"server_id": "leaf-1"}) is None
    assert get_server_id({"name": "a", "server_id": "b"}) is None


def test_get_server_id_id_wins_over_removed_keys():
    # A config the deprecation shim has NOT yet stripped: server.id wins and
    # the removed keys are ignored, so the identity is unambiguous.
    assert get_server_id({"id": "id1", "name": "n1", "server_id": "s1"}) == "id1"


def test_get_server_id_bad_inputs():
    assert get_server_id(None) is None
    assert get_server_id("not-a-dict") is None
    assert get_server_id({"id": None}) is None


def test_get_server_label_uses_description_when_set():
    assert get_server_label({"description": "Rack A hub"}) == "Rack A hub"
    assert get_server_label({"description": "Rack A hub", "id": "x"}) == "Rack A hub"


def test_get_server_label_falls_back_to_id():
    assert get_server_label({"id": "node-1"}) == "OpenMux node-1"


def test_get_server_label_falls_back_to_hostname(monkeypatch):
    monkeypatch.setattr(socket, "gethostname", lambda: FAKE_HOST)
    # No id: the hostname. The removed keys do not change the result.
    assert get_server_label({}) == f"OpenMux {FAKE_HOST}"
    assert get_server_label({"name": "n", "server_id": "s"}) == f"OpenMux {FAKE_HOST}"
    # An explicit hostname argument is used over the socket lookup.
    assert get_server_label({}, hostname=FAKE_HOSTNAME) == f"OpenMux {FAKE_HOSTNAME}"


def test_get_server_label_never_empty(monkeypatch):
    def boom():
        raise OSError("hostname unavailable")

    monkeypatch.setattr(socket, "gethostname", boom)
    # Last resort: a non-empty placeholder keeps the label usable.
    assert get_server_label({}) == "OpenMux server"


# --- Autogenerated certificate CommonName (issue #118) ---

#: Two ids that share everything up to the X.509 CommonName ceiling and differ only past it.
#: A deployment hits this for real when ids are built from a long site or rack name.
CN_PREFIX = "openmux-site-a-rack-00112233445566778899aabbccddeeff00112233445566778899"
CN_ID_A = CN_PREFIX + "-hub-primary-01"
CN_ID_B = CN_PREFIX + "-hub-secondary-02"


def test_certificate_cn_leaves_an_id_within_the_ceiling_alone():
    assert certificate_cn("node-1") == "node-1"
    # Exactly at the ceiling is not shortened: the id is what a viewer must show.
    exact = "x" * CERT_CN_MAX_LEN
    assert certificate_cn(exact) == exact


def test_certificate_cn_shortens_an_id_past_the_ceiling():
    cn = certificate_cn(CN_ID_A)
    assert len(cn) <= CERT_CN_MAX_LEN
    assert cn.startswith(CN_ID_A[:20])
    assert cn.endswith(CERT_CN_TRUNCATION_MARK + hashlib.sha256(CN_ID_A.encode("utf-8")).hexdigest()[:CERT_CN_DIGEST_LEN])
    # Deterministic: the same id yields the same label on every boot and every node.
    assert certificate_cn(CN_ID_A) == cn
    # The ceiling is absolute: a builder must never see a longer value, whatever the config holds.
    assert len(certificate_cn("x" * 5000)) == CERT_CN_MAX_LEN


def test_certificate_cn_tells_apart_ids_sharing_a_long_prefix():
    # The defect this closes: a plain cut gave both ids the same CommonName, so a person reading a
    # certificate could not tell the two nodes apart. Nothing trusts the label today, and nothing
    # should inherit that ambiguity later.
    assert len(CN_ID_A[:CERT_CN_MAX_LEN]) == len(CN_ID_B[:CERT_CN_MAX_LEN])
    assert CN_ID_A[:CERT_CN_MAX_LEN] == CN_ID_B[:CERT_CN_MAX_LEN]
    assert certificate_cn(CN_ID_A) != certificate_cn(CN_ID_B)


def test_certificate_cn_is_never_empty():
    assert certificate_cn(None, None) == "OpenMux"
    assert certificate_cn("", "") == "OpenMux"
    # A blank id is unset, so the hostname the caller supplies is the identity.
    assert certificate_cn("   ", "rack-7") == "OpenMux"
    assert certificate_cn(None, "rack-7") == "rack-7"
    # A hostname past the ceiling is shortened by the same rule as an id.
    assert len(certificate_cn(None, "h" * 200)) == CERT_CN_MAX_LEN


LOG_NAME = "test.identity.cn"


def _warn(server_section):
    """Report through a logger this module owns, against one ``server`` config section."""
    warn_long_server_id(logging.getLogger(LOG_NAME), server_section)


def test_a_long_server_id_is_reported_when_the_config_loads(caplog):
    # An operator must learn the label will differ from what they wrote, whether or not this node
    # uses TLS today. The length belongs to server.id, not to a certificate built so far.
    # A long id is rare, so this line is not background noise.
    with caplog.at_level(logging.WARNING, logger=LOG_NAME):
        caplog.clear()
        _warn({"id": CN_ID_A})

    assert f"server.id is {len(CN_ID_A)} characters" in caplog.text
    assert str(CERT_CN_MAX_LEN) in caplog.text
    assert certificate_cn(CN_ID_A) in caplog.text
    # The reassuring half belongs in the same line: nothing about a link changes.
    assert "fingerprint" in caplog.text


def test_an_identity_the_certificate_can_carry_is_not_reported(caplog, monkeypatch):
    monkeypatch.setattr(socket, "gethostname", lambda: "rack-3")
    with caplog.at_level(logging.WARNING, logger=LOG_NAME):
        caplog.clear()
        _warn({"id": "node-1"})
        _warn({"id": "x" * CERT_CN_MAX_LEN})  # exactly at the ceiling is not shortened
        _warn({})  # no id, short hostname
        _warn(None)  # no server section at all

    assert "CommonName" not in caplog.text


def test_the_hostname_fallback_is_named_by_what_to_edit(caplog, monkeypatch):
    # With no server.id the hostname is the identity, and a warning naming server.id would send the
    # operator to the wrong file.
    monkeypatch.setattr(socket, "gethostname", lambda: "h" * 200)
    with caplog.at_level(logging.WARNING, logger=LOG_NAME):
        caplog.clear()
        _warn({})

    assert "The system hostname (server.id is unset) is 200 characters" in caplog.text


def test_a_long_hostname_under_a_short_id_is_not_reported(caplog, monkeypatch):
    # The reporter follows the same chain as the certificate: an id that fits wins, so nothing a
    # certificate carries is too long and the node has nothing to fix.
    monkeypatch.setattr(socket, "gethostname", lambda: "h" * 200)
    with caplog.at_level(logging.WARNING, logger=LOG_NAME):
        caplog.clear()
        _warn({"id": "node-1"})

    assert "CommonName" not in caplog.text
