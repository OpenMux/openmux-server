"""The scenario index, generated from the collected tests instead of written by hand.

[`docs/design/e2e_test_suite.md`](../../docs/design/e2e_test_suite.md) says which scenarios exist.
This module turns each collected test into one table row, so `[`docs/E2E_TESTS.md`](../../../docs/E2E_TESTS.md)
cannot drift from the code. A test with no scenario id, no title, or no surface list is reported as
a row that says so, which fails the index test rather than hiding the gap.
"""

from __future__ import annotations

import importlib
import inspect
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence

#: Header of the generated file. Keep it stable: the freshness test compares bytes.
HEADER = """# E2E test index

Generated by `make e2e-doc` (`pytest --e2e-list`). Do not edit by hand: the command rewrites this
whole file, and the freshness test compares bytes.
Every test in `tests/e2e/` contributes one row: its scenario id, its one-line title, the surfaces it
observes, and its location. A test with no scenario id, no title, or no `e2e_surfaces` marker shows
up as `?` and fails the index test.

What each group proves is in the test inventory of
[`docs/design/e2e_test_suite.md`](design/e2e_test_suite.md); how to run the tier and how to extend a
scenario is in [`tests/e2e/README.md`](../tests/e2e/README.md).
"""

#: `test_lif01_healthz_is_anonymous` or `test_lif_01_...` produce the scenario id `LIF-01`.
_SCENARIO_ID = re.compile(r"(?P<suite>[A-Za-z]+)_?(?P<number>\d{1,3})")


@dataclass
class Row:
    """One test, as the index shows it."""

    scenario: str
    suite: str
    title: str
    surfaces: str
    location: str
    problem: str = ""

    @property
    def cells(self) -> List[str]:
        """The table cells, with a defect marker when the test is incomplete."""
        note = f" {self.problem}" if self.problem else ""
        return [self.scenario, f"{self.title}{note}", self.surfaces, f"`{self.location}`"]


def scenario_id(function_name: str) -> str:
    """The scenario id encoded in a test function name, or ``?`` when the name carries none."""
    match = _SCENARIO_ID.search(function_name.replace("test_", "", 1))
    if not match:
        return "?"
    return f"{match.group('suite').upper()}-{int(match.group('number')):02d}"


def row_for_function(module_file: Path, name: str, docstring: str, surface_args: Sequence[Any]) -> Row:
    """Build one index row from a test function's own facts.

    Args:
        module_file: The file the function lives in, for the location column.
        name: The function name, which carries the scenario id.
        docstring: The function docstring; its first line is the scenario title.
        surface_args: Arguments of the ``e2e_surfaces`` marker, if it has one.

    Returns:
        Row: the row, plus a ``problem`` string when the test is missing an id, a title, or
            surfaces.
    """
    title = docstring.strip().splitlines()[0].strip() if docstring.strip() else ""
    scenario = scenario_id(name)
    surfaces = ", ".join(str(arg) for arg in surface_args)
    location = f"tests/e2e/{module_file.name}::{name}"
    problems: List[str] = []
    if scenario == "?":
        problems.append("no scenario id in the name")
    if not title:
        problems.append("no one-line docstring")
    if not surfaces:
        problems.append("no e2e_surfaces marker")
    return Row(
        scenario=scenario,
        suite=scenario.split("-")[0] if scenario != "?" else "?",
        title=title or "?",
        surfaces=surfaces or "?",
        location=location,
        problem="(" + "; ".join(problems) + ")" if problems else "",
    )


def scan_e2e_dir(directory: Optional[Path] = None) -> List[Row]:
    """Build a row for every test function in the tier, whatever pytest was asked to run.

    The index describes the tier, not the current selection, so a run of one file must not shrink
    the committed table to one row. The modules are imported under their package name, which is the
    name pytest uses too, so nothing is imported twice.
    """
    directory = Path(directory) if directory is not None else Path(__file__).resolve().parent
    rows: List[Row] = []
    for module_path in sorted(directory.glob("test_*.py")):
        module = importlib.import_module(f"tests.e2e.{module_path.stem}")
        for name, function in vars(module).items():
            if not name.startswith("test_") or not callable(function):
                continue
            if getattr(function, "__module__", "") != module.__name__:
                continue  # an imported helper is not this file's scenario
            marks = getattr(function, "pytestmark", []) or []
            surface_args = next((mark.args for mark in marks if getattr(mark, "name", "") == "e2e_surfaces"), ())
            rows.append(row_for_function(module_path, name, inspect.getdoc(function) or "", surface_args))
    return rows


def render(rows: Sequence[Row]) -> str:
    """Render the whole index file from the collected rows."""
    lines: List[str] = [HEADER, ""]
    by_suite: Dict[str, List[Row]] = {}
    for row in rows:
        by_suite.setdefault(row.suite, []).append(row)
    for suite in sorted({row.suite for row in rows}, key=lambda name: (name == "?", name)):
        by_suite[suite].sort(key=lambda row: row.scenario)
    total = len(rows)
    lines.append(f"{total} scenarios across {max(0, len(by_suite) - (1 if '?' in by_suite else 0))} suites.")
    lines.append("")
    lines.append("| ID | Scenario | Surfaces | Test |")
    lines.append("| --- | --- | --- | --- |")
    for suite in sorted(by_suite, key=lambda name: (name == "?", name)):
        group = by_suite[suite]
        lines.append(f"| **{suite}** | | | |")
        for row in group:
            lines.append("| " + " | ".join(_escape(cell) for cell in row.cells) + " |")
    lines.append("")
    return "\n".join(lines)


def _escape(cell: str) -> str:
    """Keep one pipe from breaking a table row."""
    return cell.replace("|", "\\|")


def write_index(path: Path, rows: Sequence[Row]) -> Path:
    """Write the generated index, and create its directory when missing."""
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render(rows), encoding="utf-8")
    return target


def read_index(path: Path) -> Optional[str]:
    """The committed index text, or None when the file does not exist yet."""
    target = Path(path)
    if not target.exists():
        return None
    return target.read_text(encoding="utf-8")


def differences(committed: Optional[str], generated: str) -> List[str]:
    """The rows that differ between the committed index and a fresh generation.

    Returns:
        list of str: one line per difference, empty when the file is current. The test prints these
            and tells the reader to run `make e2e-doc`.
    """
    if committed is None:
        return ["docs/E2E_TESTS.md does not exist. Run: make e2e-doc"]
    committed_rows = _table_rows(committed)
    generated_rows = _table_rows(generated)
    out: List[str] = []
    for row in generated_rows:
        if row not in committed_rows:
            out.append(f"missing or changed: {row}")
    for row in committed_rows:
        if row not in generated_rows:
            out.append(f"stale row, no such test: {row}")
    if not out and committed.strip() != generated.strip():
        out.append("prose outside the table differs. Run: make e2e-doc")
    return out


def _table_rows(text: str) -> List[str]:
    """The body rows of the index table, with the header and suite separators dropped."""
    rows: List[str] = []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped.startswith("|"):
            continue
        if stripped.startswith("| ---") or stripped.startswith("| ID"):
            continue
        if stripped.startswith("| **"):
            continue
        rows.append(" ".join(stripped.strip("|").split()))
    return rows
